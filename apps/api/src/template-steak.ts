/** Menu, ingredients (market-rate average costs, stock zero), sub-recipes, recipes and menu options. */
export async function seedSteak(c: Tx) {
  let catSort = 0;
  const items = new Map<string, string>();
  for (const [cat, list] of STEAK_MENU) {
    const r = await c.query(`INSERT INTO menu_categories (name, sort) VALUES ($1, $2) RETURNING id`, [cat, catSort++]);
    let sort = 0;
    for (const [name, price, station] of list) {
      const it = await c.query(
        `INSERT INTO menu_items (category_id, name, price, station, sort) VALUES ($1, $2, $3, $4, $5) RETURNING id`,
        [r.rows[0].id, name, price, station, sort++]);
      items.set(name, it.rows[0].id);
    }
  }

  const ings = new Map<string, string>();
  for (const [name, kind, unit, pUnit, factor, price, yieldPct, reorder] of STEAK_INGREDIENTS) {
    const r = await c.query(
      `INSERT INTO ingredients (name, kind, base_unit, purchase_unit, purchase_factor, yield_pct, avg_cost, reorder_point)
       VALUES ($1, $2, $3, $4, $5, $6, $7, $8) RETURNING id`,
      [name, kind, unit, pUnit, factor, yieldPct, unitCostOf(price, factor), reorder]);
    ings.set(name, r.rows[0].id);
  }
  for (const [name, unit, batch] of STEAK_PREPS) {
    const r = await c.query(
      `INSERT INTO ingredients (name, kind, base_unit, purchase_unit, purchase_factor, yield_pct, avg_cost, is_prep, batch_yield)
       VALUES ($1, 'food', $2, 'ชุด', $3, 100, 0, true, $3) RETURNING id`, [name, unit, batch]);
    ings.set(name, r.rows[0].id);
  }
  for (const [name, , , lines] of STEAK_PREPS) {
    for (const [ing, qty] of lines) {
      await c.query(`INSERT INTO prep_lines (prep_id, ingredient_id, qty) VALUES ($1, $2, $3)`, [ings.get(name), ings.get(ing), qty]);
    }
  }

  for (const [item, lines] of Object.entries(STEAK_RECIPES)) {
    for (const [ing, qty] of lines) {
      await c.query(`INSERT INTO recipe_lines (menu_item_id, ingredient_id, qty) VALUES ($1, $2, $3)`, [items.get(item), ings.get(ing), qty]);
    }
  }

  let gSort = 0;
  for (const g of STEAK_OPTIONS) {
    const gr = await c.query(
      `INSERT INTO modifier_groups (name, min_select, max_select, sort) VALUES ($1, $2, $3, $4) RETURNING id`, [g.name, g.min, g.max, gSort++]);
    let oSort = 0;
    for (const o of g.options) {
      const mr = await c.query(
        `INSERT INTO modifiers (group_id, name, price, sort) VALUES ($1, $2, $3, $4) RETURNING id`, [gr.rows[0].id, o.name, o.price ?? 0, oSort++]);
      for (const [ing, qty] of o.uses ?? []) {
        await c.query(`INSERT INTO modifier_ingredients (modifier_id, ingredient_id, qty) VALUES ($1, $2, $3)`, [mr.rows[0].id, ings.get(ing), qty]);
      }
    }
    for (const name of g.items) {
      await c.query(`INSERT INTO menu_item_modifier_groups (menu_item_id, group_id) VALUES ($1, $2)`, [items.get(name), gr.rows[0].id]);
    }
  }
}
